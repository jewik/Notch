import SwiftUI

enum AngleType {
    case topLeft
    case topRight
    case bottomRight
    case bottomLeft
}

enum ContinuousCornerPath {
    /// Дискретизирует аналитическую superellipse-кривую. У её концов нулевая
    /// кривизна, поэтому профиль мягко вливается в прямые участки без дугового шва.
    static func add(
        addTo path: inout Path,
        startPoint origin: CGPoint,
        radius: CGFloat,
        angleType type: AngleType,
        inversion isInverted: Bool = false
    ) {
        let radiusF = Float(radius)
        
        var rotation: Float = 0
        var offsetX: CGFloat = 0
        var offsetY: CGFloat = 0
        
        switch type {
            case .topLeft:
                rotation = .pi
                offsetY = radius
            case .bottomLeft:
                rotation = -.pi / 2
                offsetX = radius
            case .bottomRight:
                offsetY = -radius
            case .topRight:
                rotation = .pi / 2
                offsetX = -radius
        }

        for point in SuperellipseLookup.g2_n3_samples {
            let x = point[0] * radiusF
            let y = point[1] * radiusF

            let x_rotated: CGFloat = CGFloat(x * cos(rotation) + y * sin(rotation))
            let y_rotated: CGFloat = CGFloat(x * -sin(rotation) + y * cos(rotation))

            path.addLine(to: CGPoint(
                x: origin.x + (isInverted ? y_rotated : x_rotated) + offsetX,
                y: origin.y + (isInverted ? x_rotated : y_rotated) + offsetY
            ))
        }

    }
        
}


